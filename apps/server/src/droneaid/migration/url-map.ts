import type { BundleOldUrl } from './bundle';

/**
 * Old AFFiNE URL -> new Docmost URL (pure), from the exporter's
 * `instance/old-urls.json`. Targets are root-relative paths so the same map
 * serves the canonical and the alias host.
 *
 *  - `/workspace/<ws>/<doc>` -> the page; for a published doc, its public
 *    share (AFFiNE served the public page on that same path, so visitors
 *    without an account hold these links);
 *  - `/share/<ws>/<doc>` (legacy alias) -> the share when published, else
 *    the page;
 *  - `/workspace/<ws>` and its sections (all, journals, trash, tag,
 *    collection, settings) -> the space home;
 *  - `/api/workspaces/<ws>/blobs/<key>` -> the attachment's file URL;
 *  - `/invite/<id>` -> `/login` (prefix rule, ids are not listed).
 * The query string (`lang=`, `mode=`, ...) is passed on by the Caddy rule;
 * Docmost ignores what it does not know and share pages read `lang`.
 */

export type UrlTargets = {
  page: (workspaceId: string, docId: string) => string | null;
  share: (workspaceId: string, docId: string) => string | null;
  space: (workspaceId: string) => string | null;
  blob: (workspaceId: string, key: string) => string | null;
};

export type UrlMapEntry = { from: string; to: string; kind: string };
export type UnmappedUrl = { from: string; kind: string; reason: string };

export const UNMAPPED_FALLBACK = '/home';

export function buildUrlMap(
  paths: BundleOldUrl[],
  targets: UrlTargets,
): { mapped: UrlMapEntry[]; unmapped: UnmappedUrl[] } {
  const mapped: UrlMapEntry[] = [];
  const unmapped: UnmappedUrl[] = [];
  const seen = new Set<string>();
  const add = (from: string, to: string | null, kind: string, reason: string) => {
    if (seen.has(from)) return;
    seen.add(from);
    if (to) mapped.push({ from, to, kind });
    else unmapped.push({ from, kind, reason });
  };

  for (const entry of paths) {
    const ws = entry.workspaceId ?? '';
    switch (entry.kind) {
      case 'doc':
      case 'share-legacy': {
        const docId = entry.docId ?? '';
        const share = entry.published ? targets.share(ws, docId) : null;
        add(
          entry.path,
          share ?? targets.page(ws, docId),
          entry.kind,
          'doc not imported (skipped or trashed and skipped)',
        );
        break;
      }
      case 'workspace':
      case 'tag':
      case 'collection':
        add(entry.path, targets.space(ws), entry.kind, 'workspace not imported');
        break;
      case 'blob':
        add(
          entry.path,
          targets.blob(ws, entry.targetId ?? ''),
          entry.kind,
          'blob not imported (unreferenced, or only on a canvas)',
        );
        break;
      default:
        add(entry.path, null, entry.kind, 'unknown kind');
    }
  }
  mapped.sort((a, b) => a.from.localeCompare(b.from));
  unmapped.sort((a, b) => a.from.localeCompare(b.from));
  return { mapped, unmapped };
}

const caddyQuote = (value: string) => `"${value.replace(/(["\\])/g, '\\$1')}"`;

/**
 * Caddy snippet: `import droneaid_redirects` inside the site block. One
 * `map` from the exact old path to the new one, a permanent redirect for a
 * hit (query kept with `{?query}`), `/invite/*` to login, and every other
 * old AFFiNE path (`/workspace/*`, `/share/<ws uuid>/<doc>`, old blob API)
 * to `/home`.
 */
export function caddySnippet(mapped: UrlMapEntry[], fallback = UNMAPPED_FALLBACK): string {
  const lines = [
    '# Generated by droneaid/migration import-docmost. Do not edit by hand.',
    '# Use: `import droneaid_redirects` inside the base.droneaid.fr site block.',
    '(droneaid_redirects) {',
    '\tmap {path} {droneaid_old_url} {',
    ...mapped.map((m) => `\t\t${caddyQuote(m.from)} ${caddyQuote(m.to)}`),
    '\t\tdefault ""',
    '\t}',
    '\t@droneaid_mapped expression `{droneaid_old_url} != ""`',
    '\tredir @droneaid_mapped {droneaid_old_url}{?query} 301',
    '\t@droneaid_invite path /invite/*',
    '\tredir @droneaid_invite /login 302',
    // AFFiNE share links have a workspace uuid as first segment; Docmost's
    // own `/share/<key>/p/<slug>` and `/share/p/<slug>` never match.
    '\t@droneaid_old_share path_regexp ^/share/[0-9a-f-]{36}/[^/]+$',
    `\tredir @droneaid_old_share ${fallback} 302`,
    '\t@droneaid_old path /workspace /workspace/* /api/workspaces/*',
    `\tredir @droneaid_old ${fallback} 302`,
    '}',
    '',
  ];
  return lines.join('\n');
}
