#!/usr/bin/env node
// Turns the importer's url-map.json (old AFFiNE path -> new Docmost path, written by
// `import-cli.js --out <dir>`, see droneaid/migration/import-docmost) into the Caddy
// include file `redirects.caddy`, which defines the snippet `(droneaid_redirects)`.
//
//   node droneaid/deploy/gen-redirects.mjs <import-out>/url-map.json > redirects.caddy
//
// Same rules as caddySnippet() in apps/server/src/droneaid/migration/url-map.ts (the
// importer writes an identical file next to url-map.json); this script exists so the
// include can be regenerated from the map alone, e.g. after editing a target by hand.
// Use it at the top level of the Caddyfile (`import redirects.caddy`) and then
// `import droneaid_redirects` inside the base.droneaid.fr site block.
import { readFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) {
  console.error('usage: gen-redirects.mjs <url-map.json>');
  process.exit(1);
}

const map = JSON.parse(readFileSync(file, 'utf8'));
const fallback = map.fallback ?? '/home';
if (!Array.isArray(map.mapped)) throw new Error(`${file}: no "mapped" array`);

const isPath = (v) => typeof v === 'string' && v.startsWith('/') && !/[\s{}]/.test(v);
for (const m of map.mapped) {
  if (!isPath(m.from) || !isPath(m.to)) throw new Error(`bad entry: ${JSON.stringify(m)}`);
}
if (!isPath(fallback)) throw new Error(`bad fallback: ${fallback}`);

const quote = (v) => `"${v.replace(/(["\\])/g, '\\$1')}"`;
const mapped = [...map.mapped].sort((a, b) => a.from.localeCompare(b.from));

const lines = [
  `# Generated by droneaid/deploy/gen-redirects.mjs from url-map.json (${mapped.length} entries). Do not edit by hand.`,
  '# Use: `import droneaid_redirects` inside the base.droneaid.fr site block.',
  '(droneaid_redirects) {',
  '\tmap {path} {droneaid_old_url} {',
  ...mapped.map((m) => `\t\t${quote(m.from)} ${quote(m.to)}`),
  '\t\tdefault ""',
  '\t}',
  '\t@droneaid_mapped expression `{droneaid_old_url} != ""`',
  '\tredir @droneaid_mapped {droneaid_old_url}{?query} 301',
  '\t@droneaid_invite path /invite/*',
  '\tredir @droneaid_invite /login 302',
  // AFFiNE share links have a workspace uuid as first segment; Docmost's own
  // `/share/<key>/p/<slug>` and `/share/p/<slug>` never match.
  '\t@droneaid_old_share path_regexp ^/share/[0-9a-f-]{36}/[^/]+$',
  `\tredir @droneaid_old_share ${fallback} 302`,
  '\t@droneaid_old path /workspace /workspace/* /api/workspaces/*',
  `\tredir @droneaid_old ${fallback} 302`,
  '}',
  '',
];
process.stdout.write(lines.join('\n'));
